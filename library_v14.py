"""Library operations for native cached songs and explicit local deletion."""
from pathlib import Path
import shutil

from library import Library
from maps import require
from cache_archive import CacheArchive,write_cached_material


class LibraryV14(Library):
    def read_cache(self,path,assets,log=print):
        with CacheArchive(path,assets) as archive:
            inventory=archive.inventory(log)
            cached={s['id'] for s in inventory['songs'] if s['custom']}
            known={song['level_id']:song for song in self.state['songs']}
            for entry in self.state['songs']:entry['in_viewed_cache']=entry['level_id'] in cached
            seen=set()
            for song in inventory['songs']:
                if not song['custom'] or song['id'] in seen:continue
                seen.add(song['id'])
                if song['id'] in known:
                    entry=known[song['id']];entry.update(enabled=True,in_viewed_cache=True,cached_pack=song['pack_id'])
                    continue
                log('Чтение готовой песни из кэша: '+song['title'])
                entry={'level_id':song['id'],'title':song['title'],'artist':song['artist'],
                    'difficulties':song['difficulties'],'enabled':True,'in_viewed_cache':True,
                    'cached_pack':song['pack_id'],'cache_source_obb':str(archive.path),'storage':'cache-reference',
                    'autogenerated':song['kind'] in ('AI','Старый Auto'),'warnings':[]}
                try:
                    require(song['gameplay_present'] and song['unity_header'],'В кэше отсутствуют игровые данные песни.')
                    folder,digest=write_cached_material(archive,song,self.root)
                    entry.update(storage='cached',folder=str(folder.relative_to(self.root)),hash=digest)
                except Exception as error:
                    entry['warnings'].append('Песня доступна из исходного OBB; локальное извлечение ограничено: '+str(error))
                self.state['songs'].append(entry);known[song['id']]=entry
        self.state['source_obb']=str(Path(path).resolve());self.state['cache_obb']=str(Path(path).resolve())
        self.save();return inventory

    def deletion_plan(self,identifiers):
        selected=[s for s in self.state['songs'] if s['level_id'] in set(identifiers)]
        retained=[s for s in self.state['songs'] if s['level_id'] not in set(identifiers)]
        root=self.root.resolve();folders=[]
        source_paths=[self.state.get(key) for key in ('source_obb','cache_obb','base_obb')]
        source_paths += [s.get('cache_source_obb') for s in self.state['songs']]
        sources=[Path(path).resolve() for path in source_paths if path]
        for entry in selected:
            if not entry.get('folder'):continue
            path=(self.root/entry['folder']).resolve()
            allowed=any(path.is_relative_to(root/name) and path!=root/name for name in ('maps','cache_maps'))
            require(allowed,'Удаление разрешено только внутри maps/cache_maps текущей библиотеки.')
            require(not any(source.is_relative_to(path) for source in sources),'В папке песни находится исходный OBB. Перенеси кэш за пределы папок песен перед удалением.')
            shared=any(other.get('folder') and ((self.root/other['folder']).resolve().is_relative_to(path) or path.is_relative_to((self.root/other['folder']).resolve())) for other in retained)
            if not shared and path not in folders:folders.append(path)
        return selected,folders

    def delete_local(self,identifiers):
        selected,folders=self.deletion_plan(identifiers)
        # Every target is resolved and checked before the first recursive delete.
        for folder in folders:
            if folder.exists():shutil.rmtree(folder)
        ids={s['level_id'] for s in selected}
        self.state['songs']=[s for s in self.state['songs'] if s['level_id'] not in ids]
        self.save();return len(selected)

    def outside_cache(self,inventory):
        cached={song['id'] for song in inventory['songs'] if song['custom']}
        return [song['level_id'] for song in self.state['songs'] if song['level_id'] not in cached]
