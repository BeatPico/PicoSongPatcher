"""Assemble a separate release, preserving existing libraries and programs."""
import sys,json,shutil,hashlib
from pathlib import Path
ROOT=Path(__file__).resolve().parent
sys.path[:0]=[str(ROOT.parent/'beat_saber_lab/python_packages'),str(ROOT)]
from library import Library

app=ROOT/'dist_v3/Pico Song Patcher 1.2';app.mkdir(parents=True,exist_ok=True)
source=ROOT/'ai_engine';target=app/'ai_engine'
print('Copying isolated AI runtime and pinned models...',flush=True)
def ignore(directory,names):
    return [n for n in names if n in ['.git','__pycache__','cache','.pytest_cache'] or n.endswith('.part')]
shutil.copytree(source,target,dirs_exist_ok=True,ignore=ignore)
provenance={'engine_repository':'https://github.com/fred-brenner/InfernoSaber---BeatSaber-Automapper',
    'engine_commit':'b6a559fe28d407364daeeffbd06332329707270d',
    'model_repository':'https://huggingface.co/BierHerr/InfernoSaber',
    'model_revision':'e0f4c8b53f4c52fc30c5b66fd7384c0ce85884ff',
    'runtime':'CPython 3.11.9 + TensorFlow 2.15.1 CPU',
    'adapter':'FFmpeg source decoding; upstream trained features and normalization retained',
    'network_audio_uploads':False}
(target/'provenance.json').write_text(json.dumps(provenance,indent=2),encoding='utf-8')
old=ROOT/'dist_v2/Pico Song Patcher 1.1/data'
before=hashlib.sha256((old/'library.json').read_bytes()).hexdigest()
if not (app/'data/library.json').exists():
    shutil.copytree(old,app/'data',ignore=shutil.ignore_patterns('tmp','logs'))
    library=Library(app/'data');disabled=[]
    for entry in library.state['songs']:
        if not entry.get('autogenerated'):
            entry['enabled']=False;disabled.append(entry['level_id'])
    # Copy the full-song, locally tested AI example without rerunning inference.
    tested=Library(ROOT/'validation_v12/data')
    entry=dict(tested.state['songs'][0]);source_folder=tested.root/entry['folder']
    dest=library.root/entry['folder'];shutil.copytree(source_folder,dest,dirs_exist_ok=True)
    for previous in library.state['songs']:
        if previous.get('source_audio')==entry['source_audio']:
            previous['enabled']=False;entry['replaces_level_id']=previous['level_id']
    library.state['songs'].append(entry);library.save()
    migration={'source':str(old),'source_library_sha256':before,'source_unchanged':True,
        'disabled_reported_no_data':disabled,'ai_example':entry['level_id'],
        'songs':len(library.state['songs'])}
    (library.root/'migration_v12.json').write_text(json.dumps(migration,indent=2),encoding='utf-8')
assert hashlib.sha256((old/'library.json').read_bytes()).hexdigest()==before
shutil.copy2(ROOT/'README_1.2.txt',app/'ПРОЧТИ_МЕНЯ.txt')
print('Ready:',app,flush=True)
print('Total MB:',round(sum(p.stat().st_size for p in app.rglob('*') if p.is_file())/1024**2),flush=True)
